#!/usr/bin/env python3
"""Write the function list kuna reads with --define-function @FILE.

kuna discovers functions on its own, but it finds fewer than Ghidra does in
Tornado.exe and knows none of our names. This takes the functions in
config/symbols.txt, plus Ghidra's whole function list when tools/report.py
has exported one to build/functions.txt, and writes one
`<start>[-<end>] = <name>` line per function to build/kuna-functions.txt.

    python3 tools/kuna_defs.py
    kuna decompile orig/Tornado.exe '?Read@WKZSTREAM@@QAEHPAXH@Z' \\
        --mode reliable --define-function @build/kuna-functions.txt

See docs/kuna.md.
"""

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BUILD = ROOT / "build"
NAME = re.compile(r"^[A-Za-z0-9_?@$]+$")


def read_functions(path: Path) -> dict[int, tuple[str, int]]:
    """Map address -> (name, size) for the function lines of a symbols file."""
    functions = {}
    for line in path.read_text().splitlines():
        fields = line.split()
        if len(fields) >= 3 and not line.startswith("#") and fields[2] == "function":
            size = int(fields[3], 16) if len(fields) > 3 else 0
            functions[int(fields[0], 16)] = (fields[1], size)
    return functions


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--ghidra", type=Path, default=BUILD / "functions.txt",
                        help="Ghidra function export (default: build/functions.txt, if present)")
    parser.add_argument("-o", "--output", type=Path, default=BUILD / "kuna-functions.txt")
    args = parser.parse_args()

    functions = {}
    if args.ghidra.is_file():
        functions.update(read_functions(args.ghidra))
    # Our names win; keep Ghidra's extent where symbols.txt gives no size.
    for address, (name, size) in read_functions(ROOT / "config" / "symbols.txt").items():
        functions[address] = (name, size or functions.get(address, ("", 0))[1])

    lines = ["# Generated by tools/kuna_defs.py for kuna --define-function @FILE"]
    for address in sorted(functions):
        name, size = functions[address]
        bounds = f"0x{address:x}-0x{address + size:x}" if size else f"0x{address:x}"
        # kuna names an entry only from a plain symbol; leave the rest to it.
        lines.append(f"{bounds} = {name}" if NAME.match(name) else bounds)

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines) + "\n")
    source = "symbols.txt and Ghidra" if args.ghidra.is_file() else "symbols.txt only"
    print(f"Wrote {len(functions)} functions ({source}) to {args.output}", file=sys.stderr)


if __name__ == "__main__":
    main()
