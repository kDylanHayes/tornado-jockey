// Write every function and labelled data item to a symbols file
// (config/symbols.txt format: "<address> <name> <function|data> [size]").
// Usage: analyzeHeadless <proj> <name> -process Tornado.exe -noanalysis \
//          -scriptPath tools/ghidra -postScript ExportSymbols.java <out.txt>
//@category TornadoJockey

import java.io.PrintWriter;
import java.util.TreeMap;

import ghidra.app.util.headless.HeadlessScript;
import ghidra.program.model.listing.Data;
import ghidra.program.model.listing.Function;
import ghidra.program.model.symbol.Symbol;
import ghidra.program.model.symbol.SymbolType;

public class ExportSymbols extends HeadlessScript {
	@Override
	public void run() throws Exception {
		String[] args = getScriptArgs();
		TreeMap<Long, String> lines = new TreeMap<>();

		for (Function f : currentProgram.getFunctionManager().getFunctions(true)) {
			if (f.isExternal() || f.isThunk() && f.getBody().getNumAddresses() == 0) {
				continue;
			}
			long addr = f.getEntryPoint().getOffset();
			lines.put(addr, String.format("0x%08x %s function 0x%x", addr, f.getName(true).replace(' ', '_'),
				f.getBody().getNumAddresses()));
		}

		for (Symbol s : currentProgram.getSymbolTable().getAllSymbols(true)) {
			if (s.getSymbolType() != SymbolType.LABEL || s.isExternal() || !s.isPrimary()) {
				continue;
			}
			long addr = s.getAddress().getOffset();
			if (lines.containsKey(addr)) {
				continue;
			}
			Data d = currentProgram.getListing().getDataAt(s.getAddress());
			if (d == null) {
				continue;
			}
			lines.put(addr, String.format("0x%08x %s data 0x%x", addr, s.getName(true).replace(' ', '_'), d.getLength()));
		}

		try (PrintWriter out = new PrintWriter(args[0])) {
			out.println("# Generated by tools/ghidra/ExportSymbols.java");
			for (String line : lines.values()) {
				out.println(line);
			}
		}
		println("Wrote " + lines.size() + " symbols to " + args[0]);
	}
}
