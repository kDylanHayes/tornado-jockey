#!/usr/bin/env python3
"""Generate build.ninja and objdiff.json from config/units.json."""

import argparse
import json
import os
import shlex
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent

# Best guess until the first unit matches: optimise for speed, static CRT,
# C++ exceptions on. Units can override with "cflags" in config/units.json.
DEFAULT_CFLAGS = "/nologo /c /O2 /MT /GX /W3"

PROGRESS_CATEGORIES = [
    {"id": "game", "name": "Game"},
    {"id": "engine", "name": "Tongas2 engine"},
    {"id": "lib", "name": "Third-party libraries"},
    {"id": "sdk", "name": "WildTangent SDK"},
    {"id": "crt", "name": "C/C++ runtime"},
]


def ninja_escape(s: str) -> str:
    return s.replace("$", "$$").replace(" ", "$ ").replace(":", "$:")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--msvc",
        type=Path,
        default=os.environ.get("TJ_MSVC"),
        help="Visual C++ Toolkit 2003 install folder (contains bin/cl.exe); or set TJ_MSVC",
    )
    parser.add_argument(
        "--wine",
        default=os.environ.get("TJ_WINE", "" if os.name == "nt" else "wine"),
        help="Command used to run Windows tools (empty on Windows)",
    )
    args = parser.parse_args()

    units = json.loads((ROOT / "config" / "units.json").read_text())["units"]
    categories = {c["id"] for c in PROGRESS_CATEGORIES}

    msvc = args.msvc
    if msvc is None:
        print("warning: --msvc not given; build.ninja will not be able to compile", file=sys.stderr)
        msvc = Path("MSVC_NOT_CONFIGURED")
    cl = msvc / "bin" / "cl.exe"
    def win_path(p: Path) -> str:
        # Wine maps the Unix root to drive Z:.
        p = p.resolve() if p.exists() else p
        return str(p) if not args.wine else "Z:" + str(p).replace("/", "\\")

    include = ";".join(
        win_path(p) for p in (ROOT / "include", ROOT / "src", msvc / "include")
    )

    lines = [
        "# Generated by configure.py; do not edit.",
        "ninja_required_version = 1.10",
        "",
        "rule cc",
        f"  command = env WINEDEBUG=-all INCLUDE={shlex.quote(include)} "
        f"{args.wine} {shlex.quote(str(cl))} $cflags /Fo$out $in",
        "  description = CC $in",
        "",
        "rule configure",
        f"  command = {shlex.quote(sys.executable)} configure.py "
        + (f"--msvc {shlex.quote(str(args.msvc))} " if args.msvc else "")
        + f"--wine {shlex.quote(args.wine)}",
        "  generator = 1",
        "  description = CONFIGURE",
        "",
        "build build.ninja objdiff.json: configure configure.py config/units.json",
        "",
    ]

    objdiff_units = []
    base_objects = []
    for unit in units:
        name = unit["name"]
        if unit.get("category") not in categories:
            print(f"error: unit {name} has unknown category {unit.get('category')!r}", file=sys.stderr)
            return 1
        entry = {
            "name": name,
            "target_path": unit["target"],
            "metadata": {
                "complete": bool(unit.get("complete", False)),
                "progress_categories": [unit["category"]],
            },
        }
        # Identical functions folded by the linker (/OPT:ICF) keep one name in
        # the target; map it to the name our object uses for this unit's copy.
        if unit.get("symbol_mappings"):
            entry["symbol_mappings"] = unit["symbol_mappings"]
        source = unit.get("source")
        if source:
            obj = f"build/{Path(source).with_suffix('.obj').as_posix()}"
            cflags = unit.get("cflags", DEFAULT_CFLAGS)
            lines += [
                f"build {ninja_escape(obj)}: cc {ninja_escape(source)}",
                f"  cflags = {cflags}",
                "",
            ]
            entry["base_path"] = obj
            entry["metadata"]["source_path"] = source
            base_objects.append(obj)
        objdiff_units.append(entry)

    lines += [
        "build all: phony " + " ".join(ninja_escape(o) for o in base_objects),
        "default all",
        "",
    ]
    (ROOT / "build.ninja").write_text("\n".join(lines))

    objdiff = {
        "$schema": "https://raw.githubusercontent.com/encounter/objdiff/main/config.schema.json",
        "custom_make": "ninja",
        "build_target": False,
        "build_base": True,
        "watch_patterns": ["*.c", "*.cpp", "*.h", "*.hpp", "*.inl"],
        "units": objdiff_units,
        "progress_categories": PROGRESS_CATEGORIES,
    }
    (ROOT / "objdiff.json").write_text(json.dumps(objdiff, indent=2) + "\n")
    print(f"Wrote build.ninja and objdiff.json ({len(units)} units, {len(base_objects)} with source)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
